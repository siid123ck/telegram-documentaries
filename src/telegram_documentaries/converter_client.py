"""Portrait-client seam and the image-model implementation (Phase 4).

Spike outcome (plan group 0, step 3), recorded here and in the Phase 4 notes:

- Route (a), ADK's Gemini wrapper, was assessed against the installed
  ``google-adk`` 2.14.1. ``Agent`` forwards ``generate_content_config``, so
  ``response_modalities=["IMAGE"]`` could reach the model. The image bytes would
  then be read from ADK runner events, and that path cannot be exercised offline.
- Route (b) was chosen: :class:`AdkPortraitClient` calls ``google.genai``
  directly, with one ``generate_content`` request and ``response_modalities=
  ["IMAGE"]``, and reads ``inline_data`` from the reply. It needs no ADK session
  machinery, and the seam keeps every test offline.
- No dependency was added. ``google-genai`` is already installed through
  ``google-adk``, and ``vision_client.py`` already imports it.

Importing this module is cheap and provider-free. It exposes the
:class:`PortraitClient` protocol, the pure request builder, and the timeout and
retry constants without touching the network. The provider client is built
lazily on first use, so tests run offline with an injected transport.
"""

from __future__ import annotations

import asyncio
import json
import logging
from typing import TYPE_CHECKING, Any, Protocol, runtime_checkable

from telegram_documentaries.config import MODELS
from telegram_documentaries.errors import ProviderTimeout, VisionError
from telegram_documentaries.interview_models import Dossier
from telegram_documentaries.logging_setup import log_stage
from telegram_documentaries.prompts import CONVERTER_INSTRUCTION
from telegram_documentaries.vision_client import map_provider_error

if TYPE_CHECKING:  # annotations only; never imported at runtime
    from google.genai import Client

logger = logging.getLogger(__name__)

#: Generation deadline per attempt. Image generation is far slower than the
#: 10-second text calls, so it gets its own, longer limit (requirements D9).
REQUEST_TIMEOUT_SECONDS = 60.0

#: Hard ceiling on provider calls: one attempt plus exactly one retry (D10).
MAX_ATTEMPTS = 2

#: Small, fixed backoff before the single retry, as the other model seams use.
RETRY_BACKOFF_SECONDS = 0.05

#: Telegram photos arrive as JPEG, so the source photo is sent as JPEG.
PHOTO_MIME_TYPE = "image/jpeg"

#: The only response modality requested: the portrait itself, no prose.
IMAGE_MODALITY = "IMAGE"


@runtime_checkable
class PortraitClient(Protocol):
    """Structural seam for anything that can render the hybrid portrait.

    Returns the raw generated bytes. The converter stage validates them into a
    :class:`~telegram_documentaries.converter_models.Portrait`. ``repair_note``
    is part of the signature for symmetry with the other seams; the stage never
    passes it in Phase 4 (no repair for image payloads, requirements D8).
    """

    async def render(
        self,
        photo_bytes: bytes,
        dossier: Dossier,
        /,
        *,
        repair_note: str | None = None,
    ) -> bytes:
        """Return the generated image bytes, or raise a typed error."""
        ...


class ImageTransport(Protocol):
    """The single provider call: one image request, returning the image bytes.

    Production uses :class:`GenAiImageTransport`. Tests inject a fake, so no
    socket is opened and the ADK or genai packages are never needed.
    """

    async def __call__(
        self,
        *,
        model: str,
        instruction: str,
        photo_bytes: bytes,
        request_text: str,
        response_modalities: tuple[str, ...],
    ) -> bytes:
        """Return the first generated image as bytes (empty if there is none)."""
        ...


def build_portrait_request(dossier: Dossier, repair_note: str | None) -> str:
    """Serialise the dossier and the optional note as one JSON document.

    The dossier is user-derived data. It is JSON-encoded, so quotes, newlines,
    or text that imitates instructions stay inside a string value and cannot
    change the shape of the request.
    """
    payload = {
        "suggested_animal": {
            "name": dossier.suggested_animal.name,
            "reason": dossier.suggested_animal.reason,
        },
        "quirks": [
            {"topic": quirk.topic, "observation": quirk.observation}
            for quirk in dossier.quirks
        ],
        "note": repair_note,
    }
    return json.dumps(payload, ensure_ascii=False)


def _first_image_bytes(response: Any) -> bytes:
    """Return the first inline image in a genai response, or ``b""`` if none.

    An empty result is not an error here. The converter stage rejects empty
    bytes as an invalid response, so a text-only reply never reaches Telegram.
    """
    for candidate in response.candidates or []:
        content = candidate.content
        for part in (content.parts or []) if content is not None else []:
            inline = part.inline_data
            if inline is not None and inline.data:
                data: bytes = inline.data
                return data
    return b""


class GenAiImageTransport:
    """:class:`ImageTransport` that calls ``google.genai`` directly (route b).

    The genai client is built on the first call, from the explicit key the caller
    supplies, so constructing the transport never imports genai or touches the
    network.
    """

    def __init__(self, api_key: str) -> None:
        self._api_key = api_key
        self._client: Client | None = None

    def _ensure_client(self) -> Client:
        if self._client is None:
            from google.genai import Client

            self._client = Client(api_key=self._api_key)
        return self._client

    async def __call__(
        self,
        *,
        model: str,
        instruction: str,
        photo_bytes: bytes,
        request_text: str,
        response_modalities: tuple[str, ...],
    ) -> bytes:
        from google.genai import types

        contents = [
            types.Content(
                role="user",
                parts=[
                    types.Part.from_bytes(data=photo_bytes, mime_type=PHOTO_MIME_TYPE),
                    types.Part(text=request_text),
                ],
            )
        ]
        config = types.GenerateContentConfig(
            system_instruction=instruction,
            response_modalities=list(response_modalities),
        )
        response = await self._ensure_client().aio.models.generate_content(
            model=model, contents=contents, config=config
        )
        return _first_image_bytes(response)


class AdkPortraitClient:
    """``PortraitClient`` backed by the image model (see the spike note above).

    The name follows the Phase 4 spec. The implementation uses the genai transport,
    not the ADK runner, so the module does not import the ADK at all. Pass a
    ``transport`` in tests to avoid the network.
    """

    def __init__(self, api_key: str, transport: ImageTransport | None = None) -> None:
        self._transport: ImageTransport = (
            transport if transport is not None else GenAiImageTransport(api_key)
        )

    @log_stage
    async def render(
        self,
        photo_bytes: bytes,
        dossier: Dossier,
        /,
        *,
        repair_note: str | None = None,
    ) -> bytes:
        """Render one portrait under the generation deadline; map every failure."""
        request_text = build_portrait_request(dossier, repair_note)
        try:
            return await asyncio.wait_for(
                self._transport(
                    model=MODELS["converter"],
                    instruction=CONVERTER_INSTRUCTION,
                    photo_bytes=photo_bytes,
                    request_text=request_text,
                    response_modalities=(IMAGE_MODALITY,),
                ),
                timeout=REQUEST_TIMEOUT_SECONDS,
            )
        except TimeoutError as exc:
            raise ProviderTimeout() from exc
        except VisionError:
            raise
        except Exception as exc:  # provider SDK failure; mapped, never leaked
            # Only the exception class and HTTP status are logged. The message,
            # prompt, photo, and reply never reach the log.
            status = getattr(exc, "code", None)
            logger.error(
                "portrait_provider_error error_type=%s provider_status=%s",
                type(exc).__name__,
                status if isinstance(status, int) else None,
            )
            raise map_provider_error(exc) from exc
